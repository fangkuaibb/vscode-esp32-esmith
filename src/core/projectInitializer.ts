import * as fs from 'fs';
import * as path from 'path';
import { installAgentRules } from '../agent/rules';
import { mergeJsoncFile } from './jsonc';

export type ProjectTemplate = 'blank' | 'blink';

export interface InitProjectOptions {
  projectRoot: string;
  projectName: string;
  target: string;
  template: ProjectTemplate;
  flashSize?: string;
  idfPath: string;
  idfVersion: string;
  createVscodeSettings?: boolean;
  createAgentRules?: boolean;
}

export interface InitProjectResult {
  projectName: string;
  target: string;
  template: ProjectTemplate;
  expectedPattern: string;
  created: string[];
  skipped: string[];
}

export function sanitizeProjectName(value: string): string {
  const sanitized = value
    .trim()
    .replace(/[^A-Za-z0-9_-]/g, '_')
    .replace(/^_+/, '')
    .replace(/_+$/, '');
  if (!sanitized) {
    return 'app';
  }
  return /^[0-9]/.test(sanitized) ? `app_${sanitized}` : sanitized;
}

export function targetDisplayName(target: string): string {
  const normalized = target.toLowerCase().replace(/-/g, '');
  const known: Record<string, string> = {
    esp32: 'ESP32',
    esp32s2: 'ESP32-S2',
    esp32s3: 'ESP32-S3',
    esp32c2: 'ESP32-C2',
    esp32c3: 'ESP32-C3',
    esp32c6: 'ESP32-C6',
    esp32h2: 'ESP32-H2',
    esp32p4: 'ESP32-P4',
  };
  return known[normalized] ?? target.toUpperCase();
}

function flashSizeConfig(flashSize?: string): string | undefined {
  switch (flashSize) {
    case '2MB':
      return 'CONFIG_ESPTOOLPY_FLASHSIZE_2MB=y';
    case '4MB':
      return 'CONFIG_ESPTOOLPY_FLASHSIZE_4MB=y';
    case '8MB':
      return 'CONFIG_ESPTOOLPY_FLASHSIZE_8MB=y';
    case '16MB':
      return 'CONFIG_ESPTOOLPY_FLASHSIZE_16MB=y';
    default:
      return undefined;
  }
}

function mainSource(projectName: string, template: ProjectTemplate): string {
  if (template === 'blink') {
    return `#include <stdio.h>
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "driver/gpio.h"

/*
 * 大多数 ESP32 开发板板载 LED 接在 GPIO2。
 * 如果板子不同，请修改 BLINK_GPIO。
 */
#define BLINK_GPIO GPIO_NUM_2

void app_main(void)
{
    gpio_reset_pin(BLINK_GPIO);
    gpio_set_direction(BLINK_GPIO, GPIO_MODE_OUTPUT);
    printf("ESmith blink started on GPIO%d\\n", BLINK_GPIO);

    while (1) {
        gpio_set_level(BLINK_GPIO, 1);
        vTaskDelay(pdMS_TO_TICKS(500));
        gpio_set_level(BLINK_GPIO, 0);
        vTaskDelay(pdMS_TO_TICKS(500));
    }
}
`;
  }

  return `#include <stdio.h>

void app_main(void)
{
    printf("Hello from ${projectName}!\\n");
}
`;
}

function expectedPattern(projectName: string, template: ProjectTemplate): string {
  return template === 'blink' ? 'ESmith blink started' : `Hello from ${projectName}!`;
}

function writeIfMissing(
  projectRoot: string,
  relativePath: string,
  content: string,
  result: InitProjectResult
): void {
  const filePath = path.join(projectRoot, relativePath);
  if (fs.existsSync(filePath)) {
    result.skipped.push(relativePath);
    return;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
  result.created.push(relativePath);
}

function mergeVscodeSettings(
  projectRoot: string,
  settings: Record<string, unknown>,
  result: InitProjectResult
): void {
  const relativePath = path.join('.vscode', 'settings.json');
  const filePath = path.join(projectRoot, relativePath);
  const merge = mergeJsoncFile(filePath, settings);
  if (merge.status === 'skipped') {
    result.skipped.push(`${relativePath}（${merge.reason ?? 'JSONC 无法解析'}，未修改）`);
    return;
  }
  result.created.push(merge.status === 'created' ? relativePath : `${relativePath}（已合并）`);
}

export function initializeProject(options: InitProjectOptions): InitProjectResult {
  const projectName = sanitizeProjectName(options.projectName);
  const target = options.target.toLowerCase().replace(/-/g, '') || 'esp32';
  const pattern = expectedPattern(projectName, options.template);
  const result: InitProjectResult = {
    projectName,
    target,
    template: options.template,
    expectedPattern: pattern,
    created: [],
    skipped: [],
  };

  const topCmake = `cmake_minimum_required(VERSION 3.16)
include($ENV{IDF_PATH}/tools/cmake/project.cmake)
project(${projectName})
`;
  const mainCmake = 'idf_component_register(SRCS "main.c" INCLUDE_DIRS ".")\n';

  writeIfMissing(options.projectRoot, 'CMakeLists.txt', topCmake, result);
  writeIfMissing(options.projectRoot, path.join('main', 'CMakeLists.txt'), mainCmake, result);
  writeIfMissing(options.projectRoot, path.join('main', 'main.c'), mainSource(projectName, options.template), result);

  const sdkconfigLines = [
    '# Auto-generated by ESmith',
    `CONFIG_IDF_TARGET="${target}"`,
  ];
  const sizeLine = flashSizeConfig(options.flashSize);
  if (sizeLine) {
    sdkconfigLines.push(sizeLine);
  }
  writeIfMissing(options.projectRoot, 'sdkconfig.defaults', `${sdkconfigLines.join('\n')}\n`, result);

  writeIfMissing(
    options.projectRoot,
    '.gitignore',
    [
      'build/',
      'sdkconfig',
      'sdkconfig.old',
      '.espsmith/',
      '.esmith/experience/stats.json',
      '',
    ].join('\n'),
    result
  );

  if (options.createVscodeSettings !== false) {
    mergeVscodeSettings(
      options.projectRoot,
      {
        'idf.currentSetup': options.idfPath,
        'esmith.expectedPattern': pattern,
      },
      result
    );
  }

  const metadata = {
    name: projectName,
    chip: targetDisplayName(target),
    target,
    flash_size: options.flashSize,
    idf_path: options.idfPath,
    idf_version: options.idfVersion,
    created: new Date().toISOString(),
  };
  writeIfMissing(
    options.projectRoot,
    path.join('.esmith', 'project.json'),
    `${JSON.stringify(metadata, null, 2)}\n`,
    result
  );

  if (options.createAgentRules !== false) {
    const rulePath = installAgentRules(options.projectRoot);
    result.created.push(path.relative(options.projectRoot, rulePath));
  }

  return result;
}
